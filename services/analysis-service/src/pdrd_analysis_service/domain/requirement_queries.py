"""Нормативные темы из содержания проекта, независимые от предварительных замечаний."""

import re


def independent_requirement_queries(
    *,
    discipline: str,
    text: str,
    priority_documents: tuple[str, ...] = (),
    limit: int = 4,
) -> tuple[str, ...]:
    """Добавляет ограниченный тематический поиск; приоритет документов не является фильтром корпуса."""
    context = discipline + " " + text
    topics = []
    for pattern, topic in (
        (
            r"гидрант|пожаротушени",
            "Пожарное водоснабжение: применимые требования к защищаемому объекту, "
            "видам пожаротушения, расходам и размещению гидрантов; условия выбора нормы",
        ),
        (
            r"резервуар|пожарн\w*\s+запас",
            "Резервуары и полезный пожарный запас: расчётная потребность, продолжительность, "
            "подпитка, резервирование и условия применения требований",
        ),
        (
            r"водоснабж|водопровод|труб",
            "Водоснабжение: нормативные требования к расчётным расходам, напорам, "
            "выбору диаметров, скоростям, потерям и расчётному обоснованию",
        ),
        (
            r"труб|основани|прокладк|SDR",
            "Трубопроводы: область применения стандартов материалов и труб, "
            "условия прокладки и подготовки основания; конкретные пункты и исключения",
        ),
    ):
        if re.search(pattern, context, re.I):
            topics.append(topic)
    if not topics and discipline.strip():
        topics.append(
            f"Обязательные и рекомендательные требования для дисциплины «{discipline}»: "
            "область применения, проверяемые параметры, необходимые расчётные основания"
        )
    hint = (
        (
            " Приоритет поиска: "
            + "; ".join(priority_documents)
            + ". Учитывать и остальные применимые документы."
        )
        if priority_documents
        else ""
    )
    return tuple(topic + hint for topic in topics[:limit])
