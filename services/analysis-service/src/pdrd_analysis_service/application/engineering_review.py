"""Универсальные проверочные вопросы инженерного анализа без экспертного эталона.

Вопросы направляют извлечение связей и поиск применимых норм. Они не утверждают
нарушение и не зависят от номера страницы, конкретного PDF или комментариев человека.
"""

import re

from pdrd_analysis_service.domain.analysis import PageFacts

ENGINEERING_EVIDENCE_RULES = """
ИНЖЕНЕРНАЯ ДОКАЗАТЕЛЬНОСТЬ:
- Отличай подтверждённое нарушение, конкретное подозрение needs_review и отсутствие данных.
- Для отсутствующего расчёта сначала ищи ссылку, приложение, продолжение и связанные D/T/U.
  Отсутствие на текущем листе не доказывает отсутствие во всём проекте.
- Проверяй достаточность обоснования принятого решения: исходные условия, расчёт,
  назначение параметров и область применимости. Укажи конкретное принятое значение,
  объект и недостающий шаг; общий совет «проверить расчёты» не является замечанием.
- Сопоставляй текст, план, схему, спецификацию и расчёт только для одного объекта,
  участка, режима и назначения параметра. Требуемый напор, располагаемый напор,
  аварийный сброс и подпитка не являются взаимозаменяемыми величинами.
- Пересчитай арифметику и единицы. Проверяй календарную длительность через смену года.
- Сумму сравнивай с итогом только при наличии всех строк и продолжений той же таблицы.
- Разные карты ОСР с разными вероятностями/назначением не образуют противоречие.
- Различай DN/Ду, наружный диаметр и толщину стенки; совместимость соединения
  требует типа трубы, переходника и данных изделия. Разные обозначения не доказывают дефект.
- Обрезиненный клин описывает уплотнение, не материал всей задвижки.
- Применимость СП и пунктов проверяй по переданному N и условиям объекта;
  не изобретай нормативный пункт. Сохраняй конкретные инженерные подозрения без N
  с needs_review и пустым нормативным основанием.
- Источники и области доказательства сохраняй отдельно для каждого представления.
  Нечитаемый фрагмент означает недостаточность чтения, а не доказанное нарушение.
""".strip()

_SYSTEM_QUESTIONS = (
    (
        r"водоснаб|водопровод|пожаротуш|гидрант|насос|\bв[12]\b",
        (
            "Как обоснованы расчётные расходы, запас воды, напоры, потери и скорости для каждого режима?",
            "Согласованы ли назначение систем, количество и размещение устройств в тексте, схемах и спецификации?",
        ),
    ),
    (
        r"отоплен|вентиля|теплоснаб|котель|\bов\b|\bтм\b",
        (
            "Согласованы ли тепловые нагрузки, баланс, рабочие и аварийные режимы с расчётным приложением?",
        ),
    ),
    (
        r"электр|кабел|\bэом\b|\bэс\b",
        (
            "Связаны ли расчёт нагрузок, защита, сечения, потери и режимы питания с выбранным оборудованием?",
        ),
    ),
    (
        r"автомат|контроллер|сигнализа|\bаку?\b|\bскуд\b|\bпс\b",
        (
            "Прослеживаются ли управление, обратная связь, блокировки и безопасное состояние при отказе?",
        ),
    ),
    (
        r"конструк|фундамент|грунт|сейсм|\bкр\b|\bкж\b",
        (
            "Соответствуют ли расчётные условия, нагрузки, материалы и способы строительства исходным данным?",
        ),
    ),
)


def engineering_questions(facts: PageFacts, text: str = "") -> tuple[str, ...]:
    """Выбирает вопросы по наблюдаемому содержанию, не подставляя проектные параметры."""
    content = " ".join(
        (facts.discipline, facts.summary, *facts.objects, *facts.labels, text)
    )
    questions = [
        "Какие исходные данные и расчёты обосновывают принятые технические решения?",
        "Какие связанные листы, таблицы, расчёты и спецификации описывают те же объекты и режимы?",
        "Применимы ли указанные нормативные требования к назначению системы, материалу и условиям строительства?",
        "Согласованы ли ссылки, шифры, названия, нумерация и читаемость графических листов?",
    ]
    for pattern, related in _SYSTEM_QUESTIONS:
        if re.search(pattern, content, re.IGNORECASE):
            questions.extend(related)
    return tuple(questions)
