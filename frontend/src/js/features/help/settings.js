/** Описывает ту же доступность, которую обеспечивает настоящая форма. */
export function analysisSettingAvailability(mode, { equipmentEnabled = false, explanatoryEnabled = true } = {}) {
  const pdf = mode === "pdf_only";
  return {
    "explanatory-note": explanatoryEnabled && (pdf || mode === "pdf_cad"),
    "document-context": pdf,
    "equipment-search": pdf,
    "unverified-sources": pdf && equipmentEnabled,
  };
}
